                <h2>By <a href="/legacy.php" target="_blank" rel="noopener">Pawel Osmolski</a></h2></div>
            <div class="description">
                <p>This is my homage to the <a href="http://radiohead.com/" target="_blank" rel="noreferrer">band</a>, and a gift to all the <a href="http://www.ateaseweb.com/" target="_blank" rel="noreferrer">ateaseweb</a> <a href="http://atease.radioheadnews.com" target="_blank" rel="noreferrer">board members</a>.</p>
                <p>Tracks 1, 4-6 with Thom Yorke on acoustic guitar and vocals.
                    <br /> Track 2 with Thom Yorke on piano and vocals.
                    <br /> Track 3 with Pawel Osmolski on vocals.
                    <br /> Track 5 with Jonny Greenwood on electric guitar.
                    <br /> All other instrumentation performed and arranged by Pawel Osmolski.</p>
                <p>The latest song to be remixed &quot;<a href="https://soundcloud.com/pawel-osmolski/present-tense/" target="_blank" rel="noopener">Present Tense</a>&quot; is inspired by Radiohead's soundcheck performances of the song, and a lot of listens to In Rainbows and The King of Limbs.
                    <br /> Similarly to what I did previously with <a href="https://soundcloud.com/pawel-osmolski/follow-me-around" target="_blank" rel="noopener">Follow Me Around</a>, <a href="https://soundcloud.com/pawel-osmolski/big-boots-poison-mix" target="_blank" rel="noopener">Big Boots</a> and <a href="https://soundcloud.com/pawel-osmolski/videotape-mephisto-mix" target="_blank" rel="noopener">Videotape</a>, I built up a full-band effect around an acoustic performance.</p>
                <p>I was always very fond of Thom's acoustic version played at Latitude Festival 2009-07-19, along with Jonny's version from Norwegian Wood. Thank you to the extremely clean taping by <a href="http://www.youtube.com/watch?v=BPUTSXXrh7U" target="_blank" rel="noopener">Nanakey</a>, I decided to use the Latitude recording for the basis of a remix track.</p>
                <p>Thank you to <a href="http://lanachircop.com" target="_blank" rel="noopener">Lana Chircop</a> for letting me use her awesome acrylic painting as the <a href="/assets/legacy/radiohead-remixes/presenttense.jpg" target="_blank" rel="noopener">cover art</a>.</p>
                <p>If you would like to show your thanks for the remixes, please spare a moment and listen to my album &quot;<a href="https://filiposcar.bandcamp.com/album/brokenness-trio" target="_blank" rel="noopener">Brokenness Trio</a>&quot; and the 8-bit Chiptune &quot;<a href="http://pawel-osmolski.bandcamp.com/album/space-explorer-polaris" target="_blank" rel="noopener">Space Explorer Polaris</a>&quot; on <a href="http://pawel-osmolski.bandcamp.com/" target="_blank" rel="noopener">Bandcamp</a>.</p>
