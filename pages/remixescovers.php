  <h2>Music Portfolio Brief</h2>
		<p>Here is a selective playlist of supportive and subversive remixes, as well as solo acoustic covers.<br />
A lot of my remix work is based on the idea of adding instrumentation on-top of live acoustic performances, with the goal of mimicking a full-band.<br />
It started initially after having heard a KROQ solo performance of an unreleased Radiohead song called <a href="https://soundcloud.com/pawel-osmolski/follow-me-around" target="_blank">Follow Me Around</a>. It was just an experiment, but a few of my friends suggested that I should upload a demo for people to hear. The positive feedback encouraged me to do the same for other <a href="http://www.pawel-osmolski.com/radiohead-remixes/" target="_blank">unreleased songs</a>. <a href="https://soundcloud.com/pawel-osmolski/big-boots-poison-mix" target="_blank">Big Boots</a> was a much bigger project, because instead of adding instruments to a live solo performance, it was done from scratch.<br />
Other remix works include modern recreations of Commodore 64 synth music from the 80's. The often harsh, squelchy and bleepy sounds mean that a lot of people will ignore what are otherwise brilliant and intricate pieces of music. It is my hope that the contemporary sound would allow them to be appreciated by a wider audience.</p>
